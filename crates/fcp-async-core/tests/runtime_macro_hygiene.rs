//! Compile the public runtime-test attribute in caller-controlled namespaces.
//!
//! Token-string expansion tests cannot detect attribute name resolution. Each
//! module here exercises a real consumer spelling of the shared runtime macro.

mod root_import {
    use fcp_async_core::test;

    #[test]
    async fn imported_name_runs_the_async_body() {
        assert_eq!(std::future::ready(42).await, 42);
    }

    #[test]
    async fn imported_name_preserves_result_return_type() -> Result<(), std::io::Error> {
        let value = std::future::ready(Ok::<_, std::io::Error>(42)).await?;
        assert_eq!(value, 42);
        Ok(())
    }

    #[test]
    #[should_panic(expected = "runtime-test-hygiene-sentinel")]
    async fn imported_name_preserves_harness_metadata() {
        std::future::ready(()).await;
        panic!("runtime-test-hygiene-sentinel");
    }
}

mod runtime_reexport {
    use fcp_async_core::runtime::test;

    #[test(flavor = "multi_thread")]
    async fn runtime_import_runs_with_explicit_flavor() {
        assert_eq!(std::future::ready(7).await, 7);
    }
}

mod renamed_attribute {
    // This unrelated async attribute deliberately shadows the builtin name.
    // It must not be selected by code generated by `async_test`.
    #[allow(unused_imports)]
    use fcp_async_core::main as test;
    use fcp_async_core::test as async_test;

    #[async_test]
    async fn alias_does_not_select_a_callers_unrelated_test_attribute() {
        assert!(std::future::ready(true).await);
    }
}

mod glob_import {
    #[allow(unused_imports)]
    use fcp_async_core::*;

    #[fcp_async_core::test]
    async fn qualified_invocation_ignores_a_glob_imported_test_attribute() {
        assert_eq!(std::future::ready(11).await, 11);
    }
}

mod local_core_module {
    use fcp_async_core::test;

    // A relative `core::prelude::v1::test` would resolve to this empty module.
    mod core {}

    #[test]
    async fn builtin_test_path_is_absolute() {
        assert_eq!(std::future::ready(13).await, 13);
    }
}
